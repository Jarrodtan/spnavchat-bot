// SP Navigators Chat (@spnavchat_bot)
// A 24/7 Bible verse helper. It finds Scripture; it never speaks for God.
// Personal questions and anything worrying are passed to a real leader.
//
// Secrets:
//   BOT_TOKEN       — from @BotFather
//   WEBHOOK_SECRET  — checked against Telegram's X-Telegram-Bot-Api-Secret-Token header
//   LEADER_CHAT_ID  — leaders' group chat that receives follow-up alerts

const MODEL = "@cf/zai-org/glm-4.7-flash";
const TRANSLATION = "web"; // World English Bible (public domain), via bible-api.com
const MAX_VERSES = 4;

// ============================================================
// FIXED TEXT (never generated by the model)
// ============================================================

const WELCOME =
    "👋 Hi, I'm NavChat — here 24/7.\n\n" +
    "📖 Ask me about any topic or question and I'll find Bible verses for you.\n" +
    "🙋 For personal or life questions, I'll connect you with a leader.\n" +
    "🆘 If you're in crisis, please call SOS 1767 (24 hours) or 995 for emergencies.\n\n" +
    "ℹ️ Questions passed to a leader are shared with the SP Navigators leaders so they can follow up.";

const PERSONAL_REPLY =
    "🙏 That's a really good question — and an important one to talk through with someone, not a bot.\n\n" +
    "I've let a leader know so they can reach out to you. You can also message your discipler directly anytime.";

const CRISIS_REPLY =
    "💛 I'm really glad you reached out. You don't have to go through this alone.\n\n" +
    "Please talk to someone right now:\n" +
    "📞 SOS (Samaritans of Singapore): 1767 — 24 hours\n" +
    "📞 IMH Mental Health Helpline: 6389 2222 — 24 hours\n" +
    "🚨 Emergency: 995\n\n" +
    "I've also let a leader know so they can check in with you.";

const FALLBACK_REPLY =
    "Sorry, I couldn't find verses for that just now. Try asking in a different way, or message your discipler 🙏";

// Checked before the model, so a crisis is never missed because of a model mistake
const CRISIS_WORDS = [
    "suicide", "suicidal", "kill myself", "end my life", "want to die", "self harm",
    "self-harm", "hurt myself", "cutting myself", "no reason to live", "abuse", "abused",
];

// ============================================================
// MODEL PROMPT
// ============================================================

const SYSTEM_PROMPT = `You help university students in a Christian campus ministry find Bible verses.
Classify the message and reply with JSON only, no other text:
{"type": "verses" | "personal" | "crisis" | "other", "refs": [{"ref": "Book Chapter:Verse(-Verse)", "why": "one short sentence"}]}

Rules:
- "verses": a question about a topic, doctrine, or what the Bible says. Give 1-${MAX_VERSES} well-known, relevant references.
- "personal": asks for guidance about their own life or decisions, whether God is telling them something, relationships, or struggles. refs must be [].
- "crisis": any sign of self-harm, abuse, danger, or deep distress. refs must be [].
- "other": greetings or anything unrelated to the Bible. refs must be [].
- Never claim to speak for God or the Holy Spirit. Never give personal advice.
- "why" only says what the verse is about. No interpretation of the user's situation.
- When unsure between "verses" and "personal", choose "personal".`;

// ============================================================
// TELEGRAM
// ============================================================

async function tg(env, method, body) {
    const res = await fetch(`https://api.telegram.org/bot${env.BOT_TOKEN}/${method}`, {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify(body),
    });
    if (!res.ok) console.error(`Telegram ${method} failed: ${res.status} ${await res.text()}`);
    return res;
}

const send = (env, chatId, text) =>
    tg(env, "sendMessage", { chat_id: chatId, text, disable_web_page_preview: true });

async function alertLeaders(env, from, question, kind) {
    if (!env.LEADER_CHAT_ID) return;
    const name = [from.first_name, from.last_name].filter(Boolean).join(" ");
    const handle = from.username ? ` (@${from.username})` : "";
    const icon = kind === "crisis" ? "🆘 URGENT" : "🙋 Follow-up";
    await send(env, env.LEADER_CHAT_ID,
        `${icon} — NavChat\n\nFrom: ${name}${handle}\nMessage: "${question}"\n\nPlease reach out to them.`);
}

// ============================================================
// AI + VERSES
// ============================================================

function isCrisis(text) {
    const t = text.toLowerCase();
    return CRISIS_WORDS.some(w => t.includes(w));
}

async function classify(env, question) {
    const res = await env.AI.run(MODEL, {
        messages: [
            { role: "system", content: SYSTEM_PROMPT },
            { role: "user", content: question },
        ],
        max_tokens: 400,
    });
    const raw = res?.choices?.[0]?.message?.content ?? res?.response ?? "";
    const json = String(raw).match(/\{[\s\S]*\}/);
    if (!json) throw new Error(`No JSON from model: ${raw}`);
    const data = JSON.parse(json[0]);
    return { type: data.type, refs: Array.isArray(data.refs) ? data.refs.slice(0, MAX_VERSES) : [] };
}

// Looks up the real text so the bot never quotes a verse the model made up
async function fetchVerse(ref) {
    const res = await fetch(`https://bible-api.com/${encodeURIComponent(ref)}?translation=${TRANSLATION}`);
    if (!res.ok) return null;
    const data = await res.json();
    if (!data.text) return null;
    return { ref: data.reference, text: data.text.trim().replace(/\s+/g, " ") };
}

async function answerWithVerses(refs) {
    const found = await Promise.all(refs.map(async r => {
        const v = await fetchVerse(r.ref);
        return v && `📖 ${v.ref}\n"${v.text}"\n— ${r.why}`;
    }));
    const parts = found.filter(Boolean);
    if (!parts.length) return FALLBACK_REPLY;
    return parts.join("\n\n") + "\n\n(WEB translation. Want to talk it through? Your discipler would love to hear from you 🙏)";
}

// ============================================================
// HANDLER
// ============================================================

async function handleMessage(env, msg) {
    const chatId = msg.chat.id;
    const text = (msg.text || "").trim();
    if (msg.chat.type !== "private" || !text) return;

    if (text === "/start" || text === "/help") return send(env, chatId, WELCOME);

    if (isCrisis(text)) {
        await send(env, chatId, CRISIS_REPLY);
        return alertLeaders(env, msg.from, text, "crisis");
    }

    await tg(env, "sendChatAction", { chat_id: chatId, action: "typing" });

    let result;
    try {
        result = await classify(env, text);
    } catch (err) {
        console.error(err);
        return send(env, chatId, FALLBACK_REPLY);
    }

    switch (result.type) {
        case "crisis":
            await send(env, chatId, CRISIS_REPLY);
            return alertLeaders(env, msg.from, text, "crisis");
        case "personal":
            await send(env, chatId, PERSONAL_REPLY);
            return alertLeaders(env, msg.from, text, "personal");
        case "verses":
            return send(env, chatId, await answerWithVerses(result.refs));
        default:
            return send(env, chatId, "Hi! 👋 Ask me what the Bible says about anything — e.g. \"verses about anxiety\" or \"what does the Bible say about forgiveness?\"");
    }
}

export default {
    async fetch(request, env, ctx) {
        if (request.method !== "POST") return new Response("SP Navigators Chat is running.");
        if (request.headers.get("X-Telegram-Bot-Api-Secret-Token") !== env.WEBHOOK_SECRET) {
            return new Response("Unauthorized", { status: 401 });
        }
        const update = await request.json();
        if (update.message) ctx.waitUntil(handleMessage(env, update.message).catch(console.error));
        return new Response("OK");
    },
};

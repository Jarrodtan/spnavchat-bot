// SP Navigators Chat (@spnavchat_bot)
// A 24/7 Bible verse helper. It finds Scripture; it never speaks for God.
// Personal questions and anything worrying are passed to a real leader.
//
// Secrets:
//   BOT_TOKEN       — from @BotFather
//   WEBHOOK_SECRET  — checked against Telegram's X-Telegram-Bot-Api-Secret-Token header
//   LEADER_CHAT_ID  — leaders' group chat that receives follow-up alerts
//   ESV_API_KEY     — free non-commercial key from https://api.esv.org (WEB is used until it's set)
//
// Access: only members a leader has approved can use the bot. New people get an
// Approve / Decline request in the leaders' group. Crisis replies go to everyone.

const MODEL = "@cf/meta/llama-3.3-70b-instruct-fp8-fast";
// Verse text comes from Crossway's official ESV API (free for non-commercial use)
const ESV_PARAMS = "include-passage-references=false&include-verse-numbers=false&include-footnotes=false" +
    "&include-headings=false&include-short-copyright=false&include-first-verse-numbers=false";
const MAX_VERSES = 3;
const MAX_PASSAGE = 3; // longer passages are trimmed, with a pointer to read the rest
const LINK_VERSIONS = ["NIV", "ESV", "NASB"]; // BibleGateway links under each verse

// ============================================================
// FIXED TEXT (never generated by the model)
// ============================================================

const WELCOME =
    "👋 Hi, I'm NavChat — here 24/7.\n\n" +
    "📖 Ask me about any topic or question and I'll find Bible verses for you.\n" +
    "🙋 For personal or life questions, I'll connect you with a leader.\n" +
    "🆘 If you're in crisis, please call SOS 1767 (24 hours) or 995 for emergencies.\n\n" +
    "ℹ️ Questions passed to a leader are shared with the SP Navigators leaders so they can follow up.";

const PERSONAL_REPLY =
    "🙏 That's a really good question — and an important one to talk through with someone, not a bot.\n\n" +
    "I've let a leader know so they can reach out to you. You can also message your discipler directly anytime.";

const CRISIS_REPLY =
    "💛 I'm really glad you reached out. You don't have to go through this alone.\n\n" +
    "Please talk to someone right now:\n" +
    "📞 SOS (Samaritans of Singapore): 1767 — 24 hours\n" +
    "📞 IMH Mental Health Helpline: 6389 2222 — 24 hours\n" +
    "🚨 Emergency: 995\n\n" +
    "I've also let a leader know so they can check in with you.";

const HELLO_REPLY =
    "Hi! 👋 Ask me what the Bible says about anything — e.g. \"verses about anxiety\" or \"what does the Bible say about forgiveness?\"";

const FALLBACK_REPLY =
    "Sorry, I couldn't find verses for that just now. Try asking in a different way, or message your discipler 🙏";

// Checked before the model, so a crisis is never missed because of a model mistake
const CRISIS_WORDS = [
    "suicide", "suicidal", "kill myself", "end my life", "want to die", "self harm",
    "self-harm", "hurt myself", "cutting myself", "no reason to live", "abuse", "abused",
];

// ============================================================
// MODEL PROMPT
// ============================================================

const SYSTEM_PROMPT = `You help university students in a Christian campus ministry find Bible verses.
Classify the message and reply with JSON only, no other text:
{"type": "verses" | "personal" | "crisis" | "other", "refs": [{"ref": "Book Chapter:Verse(-Verse)", "why": "one short sentence"}]}

Rules:
- "verses": a question about a topic, doctrine, or what the Bible says. Give 1-${MAX_VERSES} well-known, relevant references.
- "personal": asks for guidance about their own life or decisions, whether God is telling them something, relationships, or struggles. refs must be [].
- "crisis": any sign of self-harm, abuse, danger, or deep distress. refs must be [].
- "other": greetings or anything unrelated to the Bible. refs must be [].
- Never claim to speak for God or the Holy Spirit. Never give personal advice.
- Prefer short references (1-3 verses), not whole chapters.
- "why" is at most 6 words and only says what the verse is about. No interpretation of the user's situation.
- When unsure between "verses" and "personal", choose "personal".`;

// ============================================================
// TELEGRAM
// ============================================================

async function tg(env, method, body) {
    const res = await fetch(`https://api.telegram.org/bot${env.BOT_TOKEN}/${method}`, {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify(body),
    });
    if (!res.ok) console.error(`Telegram ${method} failed: ${res.status} ${await res.text()}`);
    return res;
}

const send = (env, chatId, text, extra = {}) =>
    tg(env, "sendMessage", { chat_id: chatId, text, disable_web_page_preview: true, ...extra });

const esc = s => String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");

async function alertLeaders(env, from, question, kind) {
    if (!env.LEADER_CHAT_ID) return;
    const name = [from.first_name, from.last_name].filter(Boolean).join(" ");
    const handle = from.username ? ` (@${from.username})` : "";
    const icon = kind === "crisis" ? "🆘 URGENT" : "🙋 Follow-up";
    await send(env, env.LEADER_CHAT_ID,
        `${icon} — NavChat\n\nFrom: ${name}${handle}\nMessage: "${question}"\n\nPlease reach out to them.`);
}

// ============================================================
// AI + VERSES
// ============================================================

function isCrisis(text) {
    const t = text.toLowerCase();
    return CRISIS_WORDS.some(w => t.includes(w));
}

// Greetings and thanks get a fixed reply, so they don't use any AI allowance
const SMALL_TALK = /^(hi+|hey+|hello+|yo|morning|good (morning|afternoon|evening|night)|thanks?( you)?|thank u|thx|ty|ok(ay)?|bye)[!. ]*$/i;

async function classify(env, question) {
    const res = await env.AI.run(MODEL, {
        messages: [
            { role: "system", content: SYSTEM_PROMPT },
            { role: "user", content: question },
        ],
        max_tokens: 250,
    });
    const raw = res?.choices?.[0]?.message?.content ?? res?.response ?? "";
    const json = String(raw).match(/\{[\s\S]*\}/);
    if (!json) throw new Error(`No JSON from model: ${raw}`);
    const data = JSON.parse(json[0]);
    return { type: data.type, refs: Array.isArray(data.refs) ? data.refs.slice(0, MAX_VERSES) : [] };
}

// Looks up the real text so the bot never quotes a verse the model made up
async function fetchVerse(env, ref) {
    return env.ESV_API_KEY ? fetchEsv(env, ref) : fetchWeb(ref);
}

// World English Bible (public domain), used until the ESV key is approved
async function fetchWeb(ref) {
    const res = await fetch(`https://bible-api.com/${encodeURIComponent(ref)}?translation=web`);
    if (!res.ok) return null;
    const data = await res.json();
    if (!data.text) return null;
    return { ref: data.reference, text: data.text.trim().replace(/\s+/g, " ") };
}

async function fetchEsv(env, ref) {
    const res = await fetch(`https://api.esv.org/v3/passage/text/?q=${encodeURIComponent(ref)}&${ESV_PARAMS}`, {
        headers: { Authorization: `Token ${env.ESV_API_KEY}` },
    });
    if (!res.ok) {
        console.error(`ESV lookup failed for ${ref}: ${res.status}`);
        return null;
    }
    const data = await res.json();
    const text = data.passages?.[0]?.trim();
    if (!text) return null;
    return { ref: data.canonical, text: text.replace(/\s+/g, " ") };
}

// "Matthew 6:25-34" -> fetch "Matthew 6:25-27" and point to the full passage
function trimRef(ref) {
    const m = ref.match(/^(.+?\d+):(\d+)-(\d+)$/);
    if (!m || +m[3] - +m[2] + 1 <= MAX_PASSAGE) return { fetchRef: ref, full: null };
    return { fetchRef: `${m[1]}:${m[2]}-${+m[2] + MAX_PASSAGE - 1}`, full: ref };
}

async function answerWithVerses(env, refs) {
    const found = await Promise.all(refs.map(async r => {
        const { fetchRef, full } = trimRef(r.ref);
        const v = await fetchVerse(env, fetchRef);
        if (!v) return null;
        const more = full ? `\n📚 Read the full passage: ${full}` : "";
        // Linking out is fine; these versions are licensed by their publishers, so their text is never shown here
        const links = LINK_VERSIONS.map(ver => {
            const url = `https://www.biblegateway.com/passage/?search=${encodeURIComponent(full || v.ref)}&version=${ver}`;
            return `<a href="${esc(url)}">${ver}</a>`;
        }).join(" · ");
        return `📖 ${esc(v.ref)}\n"${esc(v.text)}"\n— ${esc(r.why)}${esc(more)}\n🔗 Read in: ${links}`;
    }));
    const parts = found.filter(Boolean);
    if (!parts.length) return esc(FALLBACK_REPLY);
    const version = env.ESV_API_KEY ? "ESV" : "WEB translation";
    return parts.join("\n\n") + `\n\n(${version}. Want to talk it through? Your discipler would love to hear from you 🙏)`;
}

// ============================================================
// ACCESS (leader approval)
// ============================================================

const PENDING_REPLY =
    "👋 Hi! NavChat is for SP Navigators members.\n\n" +
    "I've asked a leader to approve you — I'll message you here once they do 🙏";

const STILL_PENDING_REPLY = "⏳ Still waiting for a leader to approve you. I'll message you here once they do 🙏";

const DECLINED_REPLY = "Sorry, NavChat is only for SP Navigators members. If you think this is a mistake, please talk to a leader 🙏";

const APPROVED_REPLY = "✅ You're approved! Welcome to NavChat.\n\n";

const displayName = from =>
    [from.first_name, from.last_name].filter(Boolean).join(" ") + (from.username ? ` (@${from.username})` : "");

const getUser = (env, id) => env.USERS.get(`user:${id}`, "json");
const putUser = (env, id, data) => env.USERS.put(`user:${id}`, JSON.stringify(data));

// Returns true if the person may use the bot; otherwise replies and handles the request
async function checkAccess(env, msg) {
    const user = await getUser(env, msg.from.id);
    if (user?.status === "approved") return true;
    if (user?.status === "declined") {
        await send(env, msg.chat.id, DECLINED_REPLY);
        return false;
    }
    if (user?.status === "pending") {
        await send(env, msg.chat.id, STILL_PENDING_REPLY);
        return false;
    }

    await putUser(env, msg.from.id, { status: "pending", name: displayName(msg.from), requestedAt: Date.now() });
    await send(env, msg.chat.id, PENDING_REPLY);
    await tg(env, "sendMessage", {
        chat_id: env.LEADER_CHAT_ID,
        text: `🔑 Access request — NavChat\n\n${displayName(msg.from)} wants to use NavChat.\n\nIs this an SP Navigators member?`,
        reply_markup: {
            inline_keyboard: [[
                { text: "✅ Approve", callback_data: `approve:${msg.from.id}` },
                { text: "❌ Decline", callback_data: `decline:${msg.from.id}` },
            ]],
        },
    });
    return false;
}

// A leader tapped Approve or Decline in the leaders' group
async function handleDecision(env, query) {
    const [action, userId] = String(query.data || "").split(":");
    const fromLeaders = String(query.message?.chat?.id) === String(env.LEADER_CHAT_ID);
    if (!fromLeaders || !["approve", "decline"].includes(action) || !userId) {
        return tg(env, "answerCallbackQuery", { callback_query_id: query.id, text: "Not allowed." });
    }

    const user = await getUser(env, userId) || {};
    const status = action === "approve" ? "approved" : "declined";
    await putUser(env, userId, { ...user, status, decidedBy: displayName(query.from), decidedAt: Date.now() });

    const outcome = status === "approved" ? "✅ Approved" : "❌ Declined";
    await tg(env, "editMessageText", {
        chat_id: query.message.chat.id,
        message_id: query.message.message_id,
        text: `🔑 Access request — NavChat\n\n${user.name || userId}\n\n${outcome} by ${displayName(query.from)}`,
    });
    await tg(env, "answerCallbackQuery", { callback_query_id: query.id, text: outcome });
    await send(env, userId, status === "approved" ? APPROVED_REPLY + WELCOME : DECLINED_REPLY);
}

// ============================================================
// HANDLER
// ============================================================

async function handleMessage(env, msg) {
    const chatId = msg.chat.id;
    const text = (msg.text || "").trim();
    if (msg.chat.type !== "private" || !text) return;

    // Crisis help goes to everyone, approved or not
    if (isCrisis(text)) {
        await send(env, chatId, CRISIS_REPLY);
        return alertLeaders(env, msg.from, text, "crisis");
    }

    if (!(await checkAccess(env, msg))) return;

    if (text === "/start" || text === "/help") return send(env, chatId, WELCOME);

    if (SMALL_TALK.test(text)) return send(env, chatId, HELLO_REPLY);

    await tg(env, "sendChatAction", { chat_id: chatId, action: "typing" });

    let result;
    try {
        result = await classify(env, text);
    } catch (err) {
        console.error(err);
        return send(env, chatId, FALLBACK_REPLY);
    }

    switch (result.type) {
        case "crisis":
            await send(env, chatId, CRISIS_REPLY);
            return alertLeaders(env, msg.from, text, "crisis");
        case "personal":
            await send(env, chatId, PERSONAL_REPLY);
            return alertLeaders(env, msg.from, text, "personal");
        case "verses":
            return send(env, chatId, await answerWithVerses(env, result.refs), { parse_mode: "HTML" });
        default:
            return send(env, chatId, HELLO_REPLY);
    }
}

export default {
    async fetch(request, env, ctx) {
        if (request.method !== "POST") return new Response("SP Navigators Chat is running.");
        if (request.headers.get("X-Telegram-Bot-Api-Secret-Token") !== env.WEBHOOK_SECRET) {
            return new Response("Unauthorized", { status: 401 });
        }
        const update = await request.json();
        if (update.message) ctx.waitUntil(handleMessage(env, update.message).catch(console.error));
        if (update.callback_query) ctx.waitUntil(handleDecision(env, update.callback_query).catch(console.error));
        return new Response("OK");
    },
};
